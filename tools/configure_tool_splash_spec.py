"""Give Windows PyInstaller bootloader splashes a real taskbar button.

PyInstaller's generated splash template uses wm overrideredirect . 1 to
make a borderless window. Windows excludes such windows from the taskbar.
Use a native, non-resizable window with an ordinary title bar, initially
visible on top, and clear the topmost attribute after 1.5 seconds.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re


_SPLASH_CALL = re.compile(r"(?m)^(?P<indent>[ \t]*)splash[ \t]*=[ \t]*Splash\([ \t]*$")
_TOPMOST = re.compile(r"(?m)^(?P<indent>[ \t]*)always_on_top[ \t]*=[ \t]*(?:True|False)[ \t]*,")


def configure_splash_visibility(source: str, *, title: str = "CWR Worldgen Loading") -> str:
    """Show a taskbar-visible splash without pinning it above other applications."""
    if not title.strip() or any(ch in title for ch in "{}\r\n"):
        raise ValueError("splash taskbar title must be non-empty and contain no Tcl braces")

    calls = list(_SPLASH_CALL.finditer(source))
    if len(calls) != 1:
        raise ValueError(f"expected one PyInstaller splash target, found {len(calls)}")
    call = calls[0]
    close = re.search(r"(?m)^[ \t]*\)[ \t]*$", source[call.end():])
    if close is None:
        raise ValueError("could not locate end of PyInstaller Splash() target")
    end = call.end() + close.start()
    target = source[call.end():end]
    existing = list(_TOPMOST.finditer(target))
    if len(existing) > 1:
        raise ValueError("multiple Splash always_on_top options")
    if existing:
        target = _TOPMOST.sub(r"\g<indent>always_on_top=True,", target, count=1)
    else:
        # The image path is a positional argument. Add the option only after
        # all positional arguments and the other generated keyword arguments.
        target = target.rstrip("\n") + "\n" + call.group("indent") + "    always_on_top=True,\n"

    # The same Tcl script runs in the bootloader *before* Python starts,
    # so changing our Tk application windows cannot affect this splash.
    # Fail the build if a future PyInstaller changes the template instead
    # of silently producing a splash that has no taskbar button.
    setup = (
        "from PyInstaller.building import splash_templates as _cwr_splash_templates\n"
        "if 'wm overrideredirect . 1' not in _cwr_splash_templates.position_window_on_top:\n"
        "    raise RuntimeError('PyInstaller splash window template has changed')\n"
        "_cwr_splash_templates.position_window_on_top = "
        "_cwr_splash_templates.position_window_on_top.replace("
        "'wm overrideredirect . 1', 'wm overrideredirect . 0')\n"
        "_cwr_splash_templates.raise_window += "
        + repr(
            "\nwm title . {" + title + "}\n"
            "wm resizable . 0 0\n"
            "wm protocol . WM_DELETE_WINDOW {}\n"
            "after 1500 {wm attributes . -topmost 0}\n"
        )
        + "\n\n"
    )
    if "_cwr_splash_templates.position_window_on_top" not in source:
        source = source[:call.start()] + setup + source[call.start():]
        call = _SPLASH_CALL.search(source)
        assert call is not None
        close = re.search(r"(?m)^[ \t]*\)[ \t]*$", source[call.end():])
        assert close is not None
        end = call.end() + close.start()
    return source[:call.end()] + target + source[end:]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("spec", type=Path, help="spec generated by pyi-makespec")
    args = parser.parse_args()
    spec = args.spec
    original = spec.read_text(encoding="utf-8")
    title = f"{spec.stem.replace('-', ' ')} - Loading"
    modified = configure_splash_visibility(original, title=title)
    spec.write_text(modified, encoding="utf-8")
    print(f"Configured taskbar-visible loading screen: {spec}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
