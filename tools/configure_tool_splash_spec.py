"""Make PyInstaller's one-file tool splash window non-topmost.

PyInstaller's --splash flag generates a Splash() target with the default
always_on_top=True. This build-time adjustment keeps the progress window but
allows users to switch to other applications during a long extraction.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re


_SPLASH_CALL = re.compile(r"(?m)^(?P<indent>[ \t]*)splash[ \t]*=[ \t]*Splash\([ \t]*$")
_TOPMOST = re.compile(r"(?m)^(?P<indent>[ \t]*)always_on_top[ \t]*=[ \t]*(?:True|False)[ \t]*,")


def disable_splash_always_on_top(source: str) -> str:
    """Return a modified spec; refuse nonstandard files rather than silently skip."""
    calls = list(_SPLASH_CALL.finditer(source))
    if len(calls) != 1:
        raise ValueError(f"expected one PyInstaller splash target, found {len(calls)}")
    call = calls[0]
    # The generated target closes on an unindented line. Limit edits to this
    # target instead of changing another topmost option elsewhere in the spec.
    close = re.search(r"(?m)^[ \t]*\)[ \t]*$", source[call.end():])
    if close is None:
        raise ValueError("could not locate end of PyInstaller Splash() target")
    end = call.end() + close.start()
    target = source[call.end():end]
    existing = list(_TOPMOST.finditer(target))
    if len(existing) > 1:
        raise ValueError("multiple Splash always_on_top options")
    if existing:
        target = _TOPMOST.sub(r"\g<indent>always_on_top=False,", target, count=1)
    else:
        # Splash() takes its image path as a positional argument. Put this
        # option *after* it (and after the other generated keyword arguments).
        target = target.rstrip("\n") + "\n" + call.group("indent") + "    always_on_top=False,\n"
    return source[:call.end()] + target + source[end:]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("spec", type=Path, help="spec generated by pyi-makespec")
    arguments = parser.parse_args()
    spec = arguments.spec
    original = spec.read_text(encoding="utf-8")
    modified = disable_splash_always_on_top(original)
    spec.write_text(modified, encoding="utf-8")
    print(f"Configured non-topmost loading screen: {spec}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
