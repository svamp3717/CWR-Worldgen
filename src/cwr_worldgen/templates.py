from __future__ import annotations

import re
from typing import Protocol, Sequence


WORLD_INTRO_NAME = "intro"


class _TownLocation(Protocol):
    class_name: str
    name: str
    x: float
    z: float


class _WorldConfigSpec(Protocol):
    name: str
    display_name: str
    cell_size: float

    @property
    def centre(self) -> float: ...


def render_config(
    spec: _WorldConfigSpec,
    *,
    milestone: int,
    town_names: Sequence[_TownLocation] = (),
    animated_building_models: Sequence[str] = (),
) -> str:
    centre = int(spec.centre)
    icon_filename = "icon.paa" if bool(getattr(spec, "surface_pass_enabled", False)) else "g.paa"
    names_block = ""
    if town_names:
        entries: list[str] = []
        for location in town_names:
            entries.append(
                f'''        class {location.class_name}
        {{
            name = "{location.name}";
            position[] = {{{location.x:.3f}, {location.z:.3f}, 25}};
        }};'''
            )
        names_block = "\n        class Names\n        {\n" + "\n\n".join(entries) + "\n        };"

    vehicles_block = ""
    if animated_building_models:
        base_class = f"CWR_{spec.name}_ProceduralDoorHouse"
        land_classes: list[str] = []
        for model_path in sorted(set(animated_building_models)):
            normalized_model = model_path.replace("/", "\\")
            filename = normalized_model.rsplit("\\", 1)[-1]
            stem = filename[:-4] if filename.casefold().endswith(".p3d") else filename
            land_classes.append(
                f'''    class Land_{stem}: {base_class}
    {{
        scope = 1;
        model = "\\{normalized_model}";
    }};'''
            )
        vehicles_block = f'''

class CfgVehicles
{{
    // Keep the procedural door base self-contained. OFP/CWA resolves the
    // concrete Land_<p3dName> class by its simulation token, so depending on
    // an externally declared CfgVehicles/House base makes addon load order a
    // parser dependency and can fail with "Undefined base class 'House'".
    class {base_class}
    {{
        scope = 0;
        simulation = "house";
        animated = 1;
        class Animations
        {{
            class Door1
            {{
                type = "rotation";
                animPeriod = 0.8;
                selection = "door1";
                axis = "door1_axis";
                angle0 = 0;
                angle1 = -1.570796;
            }};
        }};
        class UserActions
        {{
            class OpenDoor1
            {{
                displayName = "Open door";
                position = "door1_action";
                radius = 5.0;
                condition = "this animationPhase ""Door1"" < 0.5";
                statement = "this animate [""Door1"", 1]";
                onlyForPlayer = 1;
            }};
            class CloseDoor1
            {{
                displayName = "Close door";
                position = "door1_action";
                radius = 5.0;
                condition = "this animationPhase ""Door1"" >= 0.5";
                statement = "this animate [""Door1"", 0]";
                onlyForPlayer = 1;
            }};
            class OpenDoor1Inside
            {{
                displayName = "Open door";
                position = "door1_action_inside";
                radius = 5.0;
                condition = "this animationPhase ""Door1"" < 0.5";
                statement = "this animate [""Door1"", 1]";
                onlyForPlayer = 1;
            }};
            class CloseDoor1Inside
            {{
                displayName = "Close door";
                position = "door1_action_inside";
                radius = 5.0;
                condition = "this animationPhase ""Door1"" >= 0.5";
                statement = "this animate [""Door1"", 0]";
                onlyForPlayer = 1;
            }};
        }};
    }};

{chr(10).join(land_classes)}
}};'''

    return f'''// Generated by cwr-worldgen Milestone {milestone}.
// RVW4 and PAA output follows the legacy OFP/CWA serializer conventions.

class CfgPatches
{{
    class {spec.name}
    {{
        units[] = {{}};
        weapons[] = {{}};
        worlds[] = {{"{spec.name}"}};
        requiredVersion = 1.75;
        requiredAddons[] = {{}};
    }};
}};

class CfgWorlds
{{
    // The CWA parser rejects C++-style bare class declarations. This is the
    // traditional OFP island inheritance form used by working community maps.
    class DefaultWorld {{}};
    class Intro: DefaultWorld {{}};

    class {spec.name}: Intro
    {{
        access = 3;
        description = "{spec.display_name}";
        worldName = "\\{spec.name}\\{spec.name}.wrp";
        cutscenes[] = {{"{WORLD_INTRO_NAME}"}};
        icon = "\\{spec.name}\\data\\{icon_filename}";
        longitude = 0;
        latitude = 0;
        landGrid = {spec.cell_size:g};
        centerPosition[] = {{{centre}, {centre}, 0}};
        seagullPos[] = {{{centre}, {centre}, 100}};
        startTime = "12:00";
        startDate = "1/6/85";{names_block}
    }};
}};

class CfgWorldList
{{
    class {spec.name} {{}};
}};{vehicles_block}
'''


