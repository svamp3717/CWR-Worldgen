_BARE_CLASS_DECLARATION = re.compile(r"\bclass\s+[A-Za-z_][A-Za-z0-9_]*\s*;")


def validate_cwa_config(text: str) -> None:
    """Reject syntax known to be unsupported by the OFP/CWA config parser."""
    bare = _BARE_CLASS_DECLARATION.search(text)
    if bare:
        raise ValueError(f"CWA config contains unsupported bare class declaration: {bare.group(0)}")

    depth = 0
    in_string = False
    escaped = False
    index = 0
    while index < len(text):
        char = text[index]
        next_char = text[index + 1] if index + 1 < len(text) else ""
        if not in_string and char == "/" and next_char == "/":
            newline = text.find("\n", index + 2)
            if newline < 0:
                break
            index = newline + 1
            continue
        if in_string:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                in_string = False
        elif char == '"':
            in_string = True
        elif char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth < 0:
                raise ValueError("CWA config has an unmatched closing brace")
        index += 1

    if in_string:
        raise ValueError("CWA config has an unterminated string")
    if depth != 0:
        raise ValueError("CWA config has unbalanced braces")
