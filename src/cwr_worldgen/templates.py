from __future__ import annotations

import re
from typing import Protocol, Sequence


WORLD_INTRO_NAME = "intro"


class _TownLocation(Protocol):
    class_name: str
    name: str
    x: float
    z: float


class _WorldConfigSpec(Protocol):
    name: str
    display_name: str
    cell_size: float

    @property
    def centre(self) -> float: ...


def render_config(
    spec: _WorldConfigSpec,
    *,
    milestone: int,
    town_names: Sequence[_TownLocation] = (),
) -> str:
    centre = int(spec.centre)
    icon_filename = "icon.paa" if bool(getattr(spec, "surface_pass_enabled", False)) else "g.paa"
    names_block = ""
    if town_names:
        entries: list[str] = []
        for location in town_names:
            entries.append(
                f'''        class {location.class_name}
        {{
            name = "{location.name}";
            position[] = {{{location.x:.3f}, {location.z:.3f}, 25}};
        }};'''
            )
        names_block = "\n        class Names\n        {\n" + "\n\n".join(entries) + "\n        };"
    return f'''// Generated by cwr-worldgen Milestone {milestone}.
// RVW4 and PAA output follows the legacy OFP/CWA serializer conventions.

class CfgPatches
{{
    class {spec.name}
    {{
        units[] = {{}};
        weapons[] = {{}};
        worlds[] = {{"{spec.name}"}};
        requiredVersion = 1.75;
        requiredAddons[] = {{}};
    }};
}};

class CfgWorlds
{{
    // The CWA parser rejects C++-style bare class declarations. This is the
    // traditional OFP island inheritance form used by working community maps.
    class DefaultWorld {{}};
    class Intro: DefaultWorld {{}};

    class {spec.name}: Intro
    {{
        access = 3;
        description = "{spec.display_name}";
        worldName = "\\{spec.name}\\{spec.name}.wrp";
        // CWR-CE's menu transition assumes at least one island cutscene exists.
        // The generator writes Anims/{WORLD_INTRO_NAME}.{spec.name}/ beside Addons/.
        cutscenes[] = {{"{WORLD_INTRO_NAME}"}};
        icon = "\\{spec.name}\\data\\{icon_filename}";
        longitude = 0;
        latitude = 0;
        landGrid = {spec.cell_size:g};
        centerPosition[] = {{{centre}, {centre}, 0}};
        seagullPos[] = {{{centre}, {centre}, 100}};
        startTime = "12:00";
        startDate = "1/6/85";{names_block}
    }};
}};

class CfgWorldList
{{
    class {spec.name} {{}};
}};
'''


