_BARE_CLASS_DECLARATION = re.compile(r"\bclass\s+[A-Za-z_][A-Za-z0-9_]*\s*;")


def validate_cwa_config(text: str) -> None:
    """Reject syntax known to be unsupported by the OFP/CWA config parser."""
    bare = _BARE_CLASS_DECLARATION.search(text)
    if bare:
        raise ValueError(f"CWA config contains unsupported bare class declaration: {bare.group(0)}")

    # CWA resolves inheritance while parsing the current config tree. Generated
    # configs therefore must not inherit from an undeclared external class: a
    # reference such as ``class Foo: House`` can abort addon loading before the
    # rest of the file is parsed. Require every base used by our generated text
    # to have appeared earlier in the same file.
    declared_classes: set[str] = set()
    class_with_body = re.compile(
        r"\bclass\s+([A-Za-z_][A-Za-z0-9_]*)\s*(?::\s*([A-Za-z_][A-Za-z0-9_]*))?\s*\{"
    )
    for match in class_with_body.finditer(text):
        class_name, base_name = match.groups()
        if base_name and base_name not in declared_classes:
            raise ValueError(
                f"CWA config class {class_name} inherits from undeclared base class {base_name}"
            )
        declared_classes.add(class_name)

    depth = 0
    in_string = False
    escaped = False
    index = 0
    while index < len(text):
        char = text[index]
        next_char = text[index + 1] if index + 1 < len(text) else ""
        if not in_string and char == "/" and next_char == "/":
            newline = text.find("\n", index + 2)
            if newline < 0:
                break
            index = newline + 1
            continue
        if in_string:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                in_string = False
        elif char == '"':
            in_string = True
        elif char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth < 0:
                raise ValueError("CWA config has an unmatched closing brace")
        index += 1

    if in_string:
        raise ValueError("CWA config has an unterminated string")
    if depth != 0:
        raise ValueError("CWA config has unbalanced braces")
